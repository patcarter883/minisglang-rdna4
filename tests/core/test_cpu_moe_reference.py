"""CORRECTNESS of a CPU-tier MoE layer, against the float64 reference, on the REAL checkpoint.

This is the test the whole tier stands or falls on, and it is reachable with no GPU: the CPU tier's
input is safetensors bytes on disk and its output is a vector, so the entire numeric path can be
exercised on the host.

WHAT IT COMPARES
    `weights/cpu_worker.py`'s pure-numpy dequant-and-GEMM, driven through the real
    `CpuMoEWorker` submit/join handoff, against `tools/cpu_moe/fixture/L*/ref/y_f64.bin` — a
    float64 reference computed independently by `tools/cpu_moe/make_fixture.py` straight from the
    raw safetensors bytes, and the same reference the AVX-512 core was validated to rel_rms
    ~2e-07 against on 2026-09-04.

    So this is a THREE-way agreement: the C core, the stored reference, and the Python path the
    engine's seam actually calls. Two independent implementations of the checkpoint's NVFP4
    convention agreeing to 1e-14 is what makes the convention itself (see below) a finding rather
    than a guess.

THE FORMAT FINDING THIS TEST ENCODES
    `W = E2M1[code] * e4m3(weight_scale) * weight_scale_2`, with `weight_scale_2` a MULTIPLIER.
    `python/minisgl/quant/nvfp4.py` documents and implements llm-compressor's
    `weight_global_scale = 448*6/amax`, a DIVISOR, and keys on that NAME. This checkpoint spells it
    `weight_scale_2` and stores the RECIPROCAL. `test_the_documented_divisor_convention_is_absurd`
    is the regression: it asserts that using the documented sign produces |W| ~ 1e6, so a future
    change that "fixes" the sign to match the docstring fails loudly here instead of silently
    serving noise.

SKIPS, LOUDLY, if the fixture is absent — it is generated by
`tools/cpu_moe/make_fixture.py --out tools/cpu_moe/fixture/L0 --layer 0` against
/home/pat/.cache/hf-q4e and is ~35 KB per layer, so it is cheap to regenerate but is not checked
in as a binary blob.
"""

