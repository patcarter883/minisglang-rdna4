_HERE = os.path.dirname(os.path.abspath(__file__))
_FIXTURE = os.path.normpath(os.path.join(_HERE, "..", "..", "tools", "cpu_moe", "fixture"))


def _layers_available():
    """Fixture layers whose CHECKPOINT SHARDS are also readable from this process.

    The shard paths are absolute and baked into `plan.txt`, so the fixture is usable on the bare
    host and NOT inside the serve container unless /home/pat/.cache/hf-q4e is mounted. Checking the
    shards here rather than letting the memmap fail turns "run this in the container" from 13 red
    tests into an honest skip with the mount in the reason.
    """
    if not os.path.isdir(_FIXTURE):
        return []
    out = []
    for d in sorted(os.listdir(_FIXTURE)):
        p = os.path.join(_FIXTURE, d)
        if not (
            os.path.isfile(os.path.join(p, "meta.json"))
            and os.path.isfile(os.path.join(p, "ref", "y_f64.bin"))
        ):
            continue
        try:
            with open(os.path.join(p, "meta.json")) as f:
                shards = json.load(f).get("shards") or []
        except Exception:
            continue
        if shards and all(os.path.isfile(s) for s in shards):
            out.append(d)
    return out


_LAYERS = _layers_available()
_needs_fixture = pytest.mark.skipif(
    not _LAYERS,
    reason=(
        "CPU-MoE fixture or its checkpoint shards are unreadable from this process. The "
        "shard paths in plan.txt are ABSOLUTE, so inside the serve container the checkpoint must "
        "be mounted at the same path (-v /home/pat/.cache/hf-q4e:/home/pat/.cache/hf-q4e:ro). "
        "Regenerate the fixture with e.g. "
        "`python3 tools/cpu_moe/make_fixture.py --model /home/pat/.cache/hf-q4e --layer 0 "
        "--out tools/cpu_moe/fixture/L0` (host-only, no GPU, ~35 KB)."
    ),
)


class _Fixture:
    """One layer's fixture: the byte plan, the stored route, x, and the float64 reference y."""

    def __init__(self, name: str) -> None:
        self.dir = os.path.join(_FIXTURE, name)
        with open(os.path.join(self.dir, "meta.json")) as f:
            self.meta = json.load(f)
        ref = os.path.join(self.dir, "ref")
        self.x = np.fromfile(os.path.join(ref, "x.bin"), dtype=np.float32)
        self.sel = np.fromfile(os.path.join(ref, "sel.bin"), dtype=np.int32)
        self.rw = np.fromfile(os.path.join(ref, "rw.bin"), dtype=np.float32)
        self.y = np.fromfile(os.path.join(ref, "y_f64.bin"), dtype=np.float64)
        self.plan = self._read_plan()
        self._mm: dict[int, np.ndarray] = {}

    def _read_plan(self):
        """`E <expert> <matrix> <shard> <code_off> <code_len> <scale_off> <scale_len> <N> <K> <g>`.

        matrix 0/1/2 = gate_proj / up_proj / down_proj, matching `make_fixture.PROJ`.
        """
        entries: dict[tuple[int, int], tuple] = {}
        self.shards: list[str] = []
        with open(os.path.join(self.dir, "plan.txt")) as f:
            for line in f:
                t = line.split()
                if not t:
                    continue
                if t[0] == "SHARDS":
                    continue
                if t[0] == "EXPERTS":
                    self.n_experts = int(t[1])
                    continue
                if t[0] == "E":
                    e, m, sh = int(t[1]), int(t[2]), int(t[3])
                    entries[(e, m)] = (
                        sh, int(t[4]), int(t[5]), int(t[6]), int(t[7]),
                        int(t[8]), int(t[9]), float(t[10]),
                    )
                elif t[0].startswith("/"):
                    self.shards.append(t[0])
        return entries

    def _shard(self, i: int):
        got = self._mm.get(i)
        if got is None:
            got = np.memmap(self.shards[i], dtype=np.uint8, mode="r")
            self._mm[i] = got
        return got

    def matrix(self, expert: int, m: int):
        sh, co, cl, so, sl, n, k, g = self.plan[(expert, m)]
        buf = self._shard(sh)
        codes = np.asarray(buf[co : co + cl])
        scales = np.asarray(buf[so : so + sl])
        assert cl == n * k // 2 and sl == n * k // 16, (cl, sl, n, k)
        return dequant_nvfp4(codes, scales, g, n, k), g

    def block(self, expert: int) -> ExpertBlock:
        gate, _ = self.matrix(expert, 0)
        up, _ = self.matrix(expert, 1)
        down, _ = self.matrix(expert, 2)
        return ExpertBlock(gate=gate, up=up, down=down)

    def sparse_backend(self) -> tuple[ReferenceBackend, list[int]]:
        """A backend holding ONLY the routed experts, renumbered — the EP-local convention.

        Building all 512 would be 40 GB of float64. The renumbering is exactly
        `ExpertStackTable.local_view`'s: global id -> position in this rank's shard.
        """
        uniq = sorted(set(int(i) for i in self.sel))
        blocks = [self.block(e) for e in uniq]
        remap = {e: j for j, e in enumerate(uniq)}
        return ReferenceBackend(blocks), [remap[int(e)] for e in self.sel]


def _rel_rms(got, ref):
    return float(np.sqrt(np.mean((got - ref) ** 2)) / np.sqrt(np.mean(ref**2)))


